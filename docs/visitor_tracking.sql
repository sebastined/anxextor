create table if not exists visitor_profiles (
  fingerprint_id text primary key,
  ip_hash text not null,
  ip_encrypted text,
  last_ip text,
  country text,
  city text,
  behind_proxy boolean,
  visit_count integer not null default 0,
  scan_count integer not null default 0,
  last_visit_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create table if not exists visitor_events (
  id bigint generated by default as identity primary key,
  fingerprint_id text not null references visitor_profiles (fingerprint_id) on delete cascade,
  event_type text not null,
  created_at timestamptz not null default now()
);

create index if not exists visitor_events_fingerprint_idx
  on visitor_events (fingerprint_id, created_at desc);

create index if not exists visitor_events_type_idx
  on visitor_events (event_type, created_at desc);
